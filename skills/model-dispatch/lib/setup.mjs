/**
 * 交互式配置向导
 *
 * 首次安装后运行，引导用户配置 API Key，写入 .env。
 * 不联网、不上传，只在本地写入。
 */

import readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';
import fs from 'node:fs';
import path from 'node:path';

const PROVIDERS = [
  {
    id: 'qianwen',
    name: '千问 / 阿里云 DashScope',
    envKey: 'DASHSCOPE_API_KEY',
    url: 'https://platform.qianwenai.com/home/api-keys',
    note: '支持 Token Plan（sk-sp-）与按量付费（sk-ws-）',
  },
  {
    id: 'deepseek',
    name: 'DeepSeek 官方',
    envKey: 'DEEPSEEK_API_KEY',
    url: 'https://platform.deepseek.com',
    note: '有真实余额可查，适合作为低成本主力',
  },
  {
    id: 'openrouter',
    name: 'OpenRouter',
    envKey: 'OPENROUTER_API_KEY',
    url: 'https://openrouter.ai/keys',
    note: '一个 Key 接入 Claude / Gemini / GPT 等',
  },
];

function findEnvPath() {
  const cwdEnv = path.join(process.cwd(), '.env');
  return cwdEnv;
}

function readEnv(file) {
  if (!fs.existsSync(file)) return {};
  let text = fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '');
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (m) out[m[1]] = m[2].trim();
  }
  return out;
}

function writeEnv(file, obj) {
  const lines = [
    '# Generated by model-dispatch setup',
    '# 请勿提交到版本控制',
    '',
  ];
  for (const [k, v] of Object.entries(obj)) {
    lines.push(`${k}=${v}`);
  }
  // 无 BOM 写入
  fs.writeFileSync(file, lines.join('\n') + '\n', { encoding: 'utf8' });
}

export async function runSetup({ forceEnv = null } = {}) {
  const envPath = forceEnv || findEnvPath();
  const existing = readEnv(envPath);

  console.log('Model Dispatch 配置向导');
  console.log('');
  console.log(`配置文件: ${envPath}`);
  console.log('');
  console.log('将配置各平台的 API Key。直接回车可跳过（保留现有值/暂不配置）。');
  console.log('');

  const rl = readline.createInterface({ input, output });
  const result = { ...existing };

  try {
    for (const p of PROVIDERS) {
      const cur = existing[p.envKey];
      const curLabel = cur && !/your-key|placeholder/i.test(cur) ? '[已配置，回车保留]' : '[未配置]';
      console.log(`── ${p.name} ${curLabel}`);
      console.log(`   ${p.note}`);
      console.log(`   获取: ${p.url}`);
      let answer = '';
      try {
        answer = await rl.question('   API Key: ');
      } catch {
        answer = '';
      }
      const v = answer.trim();
      if (v) {
        result[p.envKey] = v;
        console.log('   ✓ 已记录');
      } else if (cur) {
        console.log('   保持原值');
      } else {
        console.log('   跳过');
      }
      console.log('');
    }
  } finally {
    rl.close();
  }

  const meaningful = Object.entries(result).filter(
    ([k, v]) => k.endsWith('_API_KEY') && v && !/your-key|placeholder/i.test(v),
  );

  if (meaningful.length === 0) {
    console.log('未配置任何 Key。可稍后手动编辑 .env，或设置环境变量。');
    return 1;
  }

  writeEnv(envPath, result);
  console.log(`已写入 ${envPath}`);
  console.log('');
  console.log('配置完成。下一步:');
  console.log('  node lib/cli.mjs health      检查连通性');
  console.log('  node lib/cli.mjs route "你好"  查看调度决策');
  return 0;
}
